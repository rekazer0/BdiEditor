const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto(baseURL, { waitUntil: 'networkidle' });
await page.setViewportSize({ width: 1280, height: 900 });
async function openProject() {
  await page.locator('.pen-file-menu > summary').click();
  await page.getByRole('menuitem', { name: '新建皮肤', exact: true }).click();
  await expect(page.locator('#new-project-dialog')).toBeVisible();
}
await openProject();
const project = page.locator('#new-project-dialog');
await expect(project.locator('.template-preview.is-rendered')).toHaveCount(7, { timeout: 30000 });
