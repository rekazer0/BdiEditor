await expect.poll(() => library.locator('.style-picker-item').count()).toBeLessThan(total);
await library.locator('[data-style-library-filter=all]').click();
await expect(library.locator('.style-picker-item')).toHaveCount(total);
await library.locator('.style-picker-item').first().click();
