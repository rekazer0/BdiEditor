import assert from 'node:assert/strict'
import test from 'node:test'
import { declarations, run } from './helpers/app-source.mjs'

function sharing({ activation, native = false, supported = true, outcome, format = 'bdi' } = {}) {
  const calls = []
  const bytes = new Uint8Array([80, 75, 3, 4, 7, 8])
  let tapping = false
  const context = run(declarations('shareArchiveToMobile'), {
    archive: { format },
    bdaPlatform: () => 'android',
    File, Uint8Array, DOMException,
    documentName: { textContent: `测试.${format}` },
    isIOSWeb: () => !native,
    isAndroidTauri: () => native,
    mobileShareFormat: () => ['ssf', 'sxi', 'bda'].includes(format) ? format : native ? 'bds' : 'bdi',
    exportName: (_name, format) => `测试.${format}`,
    exportArchive: async () => {
      await new Promise(setImmediate)
      calls.push('exported')
      return { bytes }
    },
    showFileOperationProgress: () => calls.push('progress'),
    updateFileOperationProgress: () => {},
    invoke: async (command, data) => calls.push({ command, ...data }),
    navigator: {
      userActivation: activation,
      canShare: () => true,
      share: supported ? async (data) => {
        const { files } = data
        assert.equal(tapping, true, 'file sharing must run inside the renewed tap')
        // A title or text is a second share item, and iOS then leaves out the input method apps.
        assert.deepEqual(Object.keys(data), ['files'])
        calls.push({ file: files[0] })
        if (outcome) throw outcome
      } : undefined,
    },
    waitForTap: async (_detail, _label, share) => {
      assert.ok(calls.includes('exported'), 'prepare bytes before asking for the share tap')
      calls.push('tap')
      tapping = true
      try { return await share() } finally { tapping = false }
    },
  })
  return { context, calls, bytes }
}

for (const activation of [undefined, { isActive: true }, { isActive: false }]) {
  test(`iOS shares prepared files from a fresh tap with activation ${JSON.stringify(activation)}`, async () => {
    const { context, calls, bytes } = sharing({ activation })
    assert.equal(await context.shareArchiveToMobile(), true)
    assert.deepEqual(calls.slice(0, 3), ['progress', 'exported', 'tap'])
    const file = calls[3].file
    assert.equal(file.name, '测试.bdi')
    // A generic MIME type would make iOS offer the file as plain data; the .bdi extension has to decide.
    assert.equal(file.type, '')
    assert.deepEqual(new Uint8Array(await file.arrayBuffer()), bytes)
  })
}

for (const format of ['ssf', 'sxi']) {
  test(`iOS shares an open .${format} to its own input method in its own format`, async () => {
    const { context, calls } = sharing({ format })
    assert.equal(await context.shareArchiveToMobile(), true)
    assert.equal(calls.find((call) => call.file).file.name, `测试.${format}`)
  })
}

test('iOS still refuses an Android-only BDA before packaging', async () => {
  const { context, calls } = sharing({ format: 'bda' })
  await assert.rejects(context.shareArchiveToMobile(), /当前格式不支持 iOS/)
  assert.deepEqual(calls, ['progress'])
})

test('unsupported file sharing is visible and fails before packaging', async () => {
  const { context, calls } = sharing({ supported: false })
  await assert.rejects(context.shareArchiveToMobile(), /不支持系统文件分享/)
  assert.deepEqual(calls, ['progress'])
})

test('iOS share cancellation and rejection keep their separate outcomes', async () => {
  const cancelled = sharing({ outcome: new DOMException('cancelled', 'AbortError') })
  assert.equal(await cancelled.context.shareArchiveToMobile(), false)
  const denied = sharing({ outcome: new DOMException('denied', 'NotAllowedError') })
  await assert.rejects(denied.context.shareArchiveToMobile(), { name: 'NotAllowedError' })
})

test('Android native sharing continues to hand the generated bytes to its plugin', async () => {
  const { context, calls, bytes } = sharing({ native: true, supported: false })
  assert.equal(await context.shareArchiveToMobile(), true)
  assert.equal(calls[0], 'exported')
  assert.equal(calls[1].command, 'share_file')
  assert.equal(calls[1].name, '测试.bds')
  assert.deepEqual(calls[1].data, bytes)
  assert.equal(calls.includes('tap'), false)
})
